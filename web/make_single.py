# Builds KalliFunghi.html: the page as ONE file (styles, uPlot and the scripts inlined),
# for copying to a phone or PC as a local file. index.html with its separate files stays
# the source and the hosted version. Run after changing the page:
#   "C:\Program Files\KiCad\10.0\bin\python.exe" web\make_single.py
# The GitHub Pages workflow runs it too and checks that the committed copy is current.

import base64
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "KalliFunghi.html")


def read(name):
    with open(os.path.join(HERE, name), "r", encoding="utf-8") as f:
        return f.read()


def build():
    html = read("index.html")

    def css(m):
        return "<style>\n" + read(m.group(1)) + "\n</style>"

    def js(m):
        body = read(m.group(1)).replace("</script", "<\\/script")
        return "<script>\n" + body + "\n</script>"

    html = re.sub(r'<link rel="stylesheet" href="([^"]+)">', css, html)
    html = re.sub(r'<script src="([^"]+)"></script>', js, html)
    # A local file has no manifest or service worker; the icon goes inline.
    html = re.sub(r'<link rel="manifest"[^>]*>\n', "", html)
    icon = base64.b64encode(read("icon.svg").encode("utf-8")).decode("ascii")
    html = re.sub(r'<link rel="icon" href="icon.svg"[^>]*>',
                  '<link rel="icon" href="data:image/svg+xml;base64,%s">' % icon, html)
    html = html.replace("<!doctype html>\n",
                        "<!doctype html>\n<!-- Generated by web/make_single.py from index.html: do not edit. -->\n", 1)
    if re.search(r'<script src=|<link rel="stylesheet"', html):
        raise SystemExit("make_single.py: a script or stylesheet was not inlined")
    return html


if __name__ == "__main__":
    out = build()
    if "--check" in sys.argv:
        with open(OUT, "r", encoding="utf-8") as f:
            if f.read() != out:
                raise SystemExit("KalliFunghi.html is out of date: run web/make_single.py")
        print("KalliFunghi.html is current")
    else:
        with open(OUT, "w", encoding="utf-8", newline="\n") as f:
            f.write(out)
        print("wrote %s (%d KB)" % (OUT, len(out.encode("utf-8")) // 1024))
